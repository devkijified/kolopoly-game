-- Kolopoly finished-game records: one row per finished game.
-- Run once in the Supabase SQL editor for the records project.
-- The game server is the only accessor, through the service role key,
-- so row level security stays on with no public policies at all.

create table if not exists public.kolopoly_matches (
  id bigint generated by default as identity primary key,
  played_at timestamptz not null default now(),
  room_code text not null,
  mode text not null,
  player_count int not null,
  winner_name text not null,
  winner_net_worth bigint not null,
  players jsonb not null
);

alter table public.kolopoly_matches enable row level security;

-- Service role only. No anon or authenticated grants on purpose:
-- nothing but the game server should ever touch this table.
grant select, insert, update, delete on public.kolopoly_matches to service_role;

-- Identity inserts need sequence usage.
grant usage, select on sequence public.kolopoly_matches_id_seq to service_role;
